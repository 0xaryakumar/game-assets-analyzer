"""Authenticity signals: how much of this repository looks machine-written.

Every value is a count or a ratio. No path, no comment text, no author and no commit
message is kept, because `emit_allowlist` refuses all four and because a submitter runs
this on a machine we do not control.

The comment and test patterns come from the platform's own `ai_signals` module. The
commit-trailer count runs inside `git rev-list`, so no message text enters this process.
"""

from __future__ import annotations

import re
import statistics
import subprocess
import sys
from pathlib import Path
from typing import Any

#: One agent list, from the union of the two the platform already keeps. A name that only
#: one of them carries is still a name that identifies generated work.
#:
#: `git --grep` takes POSIX extended regular expressions, which have no `\b`, and
#: `--perl-regexp` needs a git that is built with PCRE. So the boundary is spelt out: a
#: character that is not a letter or a digit on each side. Without it `amp` matches inside
#: "Campbell" and "example", and a human co-author counts as an agent.
_AI_COAUTHOR_GREP = (
    r"co-authored-by:.*[^[:alnum:]]"
    r"(claude|copilot|cursor|devin|codeium|aider|gpt-?[0-9]|chatgpt|openai|anthropic"
    r"|gemini|windsurf|sourcegraph|amp|codex|jules|bolt)"
    r"([^[:alnum:]]|$)"
)

#: A generator declaration is not evidence of a model. Protobuf stubs and ORM models are
#: ordinary, but they are not authored lines, and price follows authored lines.
_GENERATED_MARKER = re.compile(
    r"(@generated\b|DO NOT EDIT|Code generated by|autogenerated|auto-generated"
    r"|This file was generated|Generated by the protocol buffer)",
    re.IGNORECASE,
)

#: The whole phrase, not a model name near a verb: code that builds a prompt says
#: "claude" too.
_LLM_MARKER = re.compile(
    r"(generated (?:by|with|using) (?:claude|chatgpt|gpt-?[0-9]|copilot|cursor|an? ai)\b"
    r"|written by (?:claude|chatgpt|copilot|an? ai)\b"
    r"|\bAI[- ]generated\b|created (?:by|with) (?:claude|chatgpt|copilot)\b)",
    re.IGNORECASE,
)

#: A comment that repeats the line below it instead of giving a reason.
_RESTATING = re.compile(
    r"^\s*(?://|#)\s*(?:now\s+)?("
    r"increment|decrement|initiali[sz]e|instantiate|declare|define|create|set|get|return"
    r"|loop (?:through|over)|iterate (?:through|over)|check if|if the|add|append|remove"
    r"|call|invoke|assign|store|save|update|convert|parse|import|close|open"
    r")\b[^.]{0,60}$",
    re.IGNORECASE,
)

#: A claim about the code that the code cannot support.
_UNEVIDENCED_CLAIM = re.compile(
    r"(?://|#|\*)\s*.{0,40}\b("
    r"handles all (?:edge )?cases|covers all cases|fully tested|production[- ]ready"
    r"|highly optimi[sz]ed|optimi[sz]ed for performance|thread[- ]safe by design"
    r"|robust (?:error )?handling|comprehensive (?:error )?handling|battle[- ]tested"
    r"|for maximum (?:performance|efficiency)|best practice[s]?\b"
    r")\b",
    re.IGNORECASE,
)

_MOCK_ASSERT = re.compile(
    r"\b(assert_called(?:_once)?(?:_with)?|toHaveBeenCalled(?:With|Times)?|verify\s*\("
    r"|\.called\b|Mockito\.verify)\b"
)
_REAL_ASSERT = re.compile(
    r"\b(assert(?:Equals?|True|False|Raises|In|That|Almost)?\b"
    r"|expect\s*\([^)]*\)\s*\.\s*to(?:Be|Equal|Match|Contain|Throw)|should\.)"
)

_COMMENT_LINE = re.compile(r"^\s*(//|#|\*|/\*)")
_TEST_PATH = re.compile(
    r"(^|[/_.-])(test|tests|testing|spec|specs|__tests__)([/_.-]|$)", re.I)

_SKIP_DIRS = frozenset({
    ".git", ".hg", ".svn", "node_modules", "vendor", "vendored", "third_party",
    "thirdparty", "third-party", "external", "externals", "bower_components", "Pods",
    ".venv", "venv", "env", "site-packages", "dist", "build", "out", "target",
    ".next", ".nuxt", ".tox", "__pycache__", ".gradle", ".idea", ".mypy_cache",
})

#: Wider than the list this is taken from, because that list serves company identity, where
#: a missed language costs one signal among six. Here it decides whether a repository is
#: measured at all: a tree the extensions do not name scans no file and reports nothing.
_SOURCE_SUFFIXES = frozenset({
    ".py", ".js", ".jsx", ".ts", ".tsx", ".go", ".rs", ".java", ".kt", ".kts", ".scala",
    ".rb", ".php", ".c", ".h", ".cc", ".cpp", ".cxx", ".hpp", ".hh", ".cs", ".swift",
    ".m", ".mm", ".sh", ".bash", ".zsh", ".ps1", ".psm1", ".sql", ".tf", ".vue",
    ".svelte", ".astro", ".ex", ".exs", ".erl", ".clj", ".cljs", ".groovy", ".pl", ".pm",
    ".dart", ".lua", ".hs", ".jl", ".r", ".ml", ".mli", ".fs", ".fsx", ".nim", ".zig",
    ".cr", ".elm", ".sol", ".vb", ".f90", ".cjs", ".mjs", ".rake",
})

#: A time bound, not a memory one: one float is kept for each file, and reading costs about
#: a third of a millisecond each. This budget is some seconds of a run that takes tens of
#: minutes, and it is above the file count of the repositories we buy, so the sample below
#: is the rare path.
_MAX_FILES = 50_000
_MAX_FILE_BYTES = 400_000
#: About fifteen megabytes of path strings. A set larger than this is not divided into a
#: ratio: the result would be a floor, which reads as a cleaner repository.
_MAX_PATHS = 200_000
#: Below this many files a median comment density describes nothing.
_MIN_FILES_FOR_OUTLIERS = 12


def _git(repo: Path, *args: str) -> str:
    try:
        done = subprocess.run(
            ["git", "-C", str(repo), *args],
            capture_output=True, text=True, encoding="utf-8", errors="replace", check=True,
        )
        return done.stdout
    except (subprocess.CalledProcessError, OSError) as exc:
        sys.stderr.write(f"authenticity: git {args[0]} unavailable: {exc}\n")
        return ""


def _count(repo: Path, *args: str) -> int | None:
    raw = _git(repo, *args).strip()
    return int(raw) if raw.isdigit() else None


def _git_paths(repo: Path, *args: str) -> set[str] | None:
    """The distinct non-empty lines of a git command, read as they arrive.

    `git log --all --name-only` prints one line for each file in each commit, so a deep
    history prints far more than it holds. Reading it whole puts all of that in memory for
    a set that is much smaller.

    `None` when git cannot answer, and also when the answer is larger than `_MAX_PATHS`.
    A truncated set divides to a ratio that is too low, which reads as a cleaner
    repository, so the bound reports nothing rather than a floor. The drop goes to stderr,
    per the no-silent-caps rule this skill keeps.
    """
    found: set[str] = set()
    try:
        with subprocess.Popen(
            ["git", "-C", str(repo), *args],
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, encoding="utf-8", errors="replace",
        ) as proc:
            for line in proc.stdout:
                line = line.strip()
                if line:
                    found.add(line)
                    if len(found) >= _MAX_PATHS:
                        proc.kill()
                        proc.wait()
                        sys.stderr.write(
                            f"authenticity: git {args[0]} passed {_MAX_PATHS} distinct "
                            f"paths; the ratios that read it report null\n")
                        return None
            proc.wait()
            # Whatever git printed before it failed is a part of the answer, not the answer.
            # An empty set is "this commit carries no file"; a failure is "we do not know",
            # and the two divide into very different ratios.
            if proc.returncode != 0:
                sys.stderr.write(
                    f"authenticity: git {args[0]} exited {proc.returncode}\n")
                return None
    except OSError as exc:
        sys.stderr.write(f"authenticity: git {args[0]} unavailable: {exc}\n")
        return None
    return found


def _iter_source(repo: Path) -> list[Path]:
    """Every source file, or an even sample of them when there are more than the budget.

    Walking costs about a hundredth of what reading costs, so the whole tree is listed
    before anything is read. Past the budget the sample takes every n-th path of the sorted
    list: sorted paths group by directory, so each directory gives the same share of its
    files. Stopping the walk instead would read all of one directory and none of another,
    and a median over that describes the directory that sorted last.
    """
    found: list[Path] = []
    stack = [repo]
    while stack:
        current = stack.pop()
        try:
            entries = sorted(current.iterdir())
        except OSError:
            continue
        for entry in entries:
            # A link to an ancestor makes an endless walk. A submitter controls this tree,
            # so the walk refuses every link instead of remembering where it has been.
            if entry.is_symlink():
                continue
            if entry.is_dir():
                if entry.name not in _SKIP_DIRS:
                    stack.append(entry)
            elif entry.suffix.lower() in _SOURCE_SUFFIXES:
                found.append(entry)

    found.sort()
    if len(found) <= _MAX_FILES:
        return found
    sys.stderr.write(
        f"authenticity: {len(found)} source files, sampling {_MAX_FILES} evenly\n")
    step = len(found) / _MAX_FILES
    return [found[int(index * step)] for index in range(_MAX_FILES)]


def _read(path: Path) -> str:
    try:
        with path.open("rb") as handle:
            return handle.read(_MAX_FILE_BYTES).decode("utf-8", "replace")
    except OSError:
        return ""


def _scan_files(repo: Path) -> dict[str, Any]:
    ratios: list[float] = []
    comment_chars = comments = 0
    restating = unevidenced = llm = generated = 0
    mock = real = 0

    for path in _iter_source(repo):
        text = _read(path)
        if not text:
            continue
        lines = text.splitlines()
        if not lines:
            continue

        is_test = bool(_TEST_PATH.search(str(path.relative_to(repo))))
        comment_lines = 0
        for number, line in enumerate(lines, start=1):
            if _COMMENT_LINE.match(line):
                comment_lines += 1
                comments += 1
                comment_chars += len(line.strip())
                if _RESTATING.match(line):
                    restating += 1
                if _UNEVIDENCED_CLAIM.search(line):
                    unevidenced += 1
            if number <= 40:
                if _LLM_MARKER.search(line):
                    llm += 1
                if _GENERATED_MARKER.search(line):
                    generated += 1
            if is_test:
                mock += len(_MOCK_ASSERT.findall(line))
                real += len(_REAL_ASSERT.findall(line))

        ratios.append(comment_lines / len(lines))

    median = statistics.median(ratios) if ratios else None
    outliers = None
    if len(ratios) >= _MIN_FILES_FOR_OUTLIERS and median is not None:
        # Relative to this repository, never to a global idea of enough comments. The floor
        # stops a repository with almost no comments from calling every commented file odd.
        threshold = max(0.25, median * 2.5)
        outliers = sum(1 for ratio in ratios if ratio > threshold)

    return {
        "files_scanned": len(ratios),
        "comment_ratio_median": round(median, 4) if median is not None else None,
        "comment_length_mean": round(comment_chars / comments, 1) if comments else None,
        "comment_outlier_files": outliers,
        "restating_hits": restating,
        "unevidenced_claim_hits": unevidenced,
        "llm_marker_hits": llm,
        "generated_marker_hits": generated,
        "mock_assertion_count": mock,
        "real_assertion_count": real,
    }


def _coauthor_ratio(repo: Path) -> float | None:
    total = _count(repo, "rev-list", "--count", "HEAD")
    if not total:
        return None
    matched = _count(
        repo, "rev-list", "--count", "HEAD",
        "--extended-regexp", "--regexp-ignore-case", f"--grep={_AI_COAUTHOR_GREP}",
    )
    return round(matched / total, 4) if matched is not None else None


def _top_contributor_share(repo: Path) -> float | None:
    raw = _git(repo, "shortlog", "-sn", "--no-merges", "HEAD")
    counts = []
    for line in raw.splitlines():
        head = line.strip().split("\t", 1)[0]
        if head.isdigit():
            counts.append(int(head))
    total = sum(counts)
    return round(max(counts) / total, 4) if total else None


_UNREADABLE_HISTORY = {"reachable_to_head_ratio": None, "initial_commit_share": None}


def _path_ratios(repo: Path) -> dict[str, Any]:
    # A shallow clone keeps a tip whose parents were never fetched, so git calls that tip a
    # root commit. Both ratios then describe the fetch depth: the whole tree looks like it
    # arrived in one commit, which is the shape this measure exists to report. Neither
    # question can be answered without the history, so neither is answered.
    if _git(repo, "rev-parse", "--is-shallow-repository").strip() == "true":
        return dict(_UNREADABLE_HISTORY)

    head = _git_paths(repo, "ls-tree", "-r", "--name-only", "HEAD")
    if not head:
        return dict(_UNREADABLE_HISTORY)

    # `--no-renames` keeps the old path of a move in the output. With rename detection on,
    # git prints only the new one, so a directory that moved never enlarges the history and
    # the ratio reads lower than the measurement this follows.
    reachable = _git_paths(
        repo, "log", "--all", "--name-only", "--no-renames", "--format=")

    roots = [sha for sha in _git(repo, "rev-list", "--max-parents=0", "HEAD").split() if sha]
    # An empty set and an unread root are different answers. A repository whose first commit
    # carries no file is ordinary, and the share it earns is zero, not nothing.
    seeded: set[str] | None = set() if roots else None
    for root in roots:
        found = _git_paths(repo, "show", "--name-only", "--no-renames", "--format=", root)
        if found is None:
            seeded = None
            break
        seeded |= found

    return {
        "reachable_to_head_ratio": round(len(reachable) / len(head), 4) if reachable else None,
        "initial_commit_share":
            round(len(seeded & head) / len(head), 4) if seeded is not None else None,
    }


def collect(repo: Path) -> dict[str, Any]:
    """Every authenticity signal this skill can read without a network call.

    The two author signals read `HEAD`, and the path ratios read every ref. That is on
    purpose: who wrote the code we buy is a question about the branch that ships, while
    what a repository has ever carried is a question about all of them. An abandoned branch
    belongs in the second answer and not in the first.
    """
    block = _scan_files(repo)
    block["explicit_ai_coauthor_ratio"] = _coauthor_ratio(repo)
    block["top_contributor_share"] = _top_contributor_share(repo)
    block.update(_path_ratios(repo))
    return block
